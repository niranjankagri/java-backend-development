package jbdl.session09;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.math.BigDecimal;
import java.util.Arrays;
import java.util.List;
import jbdl.session09.orders.Order;
import jbdl.session09.orders.OrderRequest;
import jbdl.session09.orders.OrderService;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

/**
 * Topic 3 (Lombok): checks that the code Lombok generates at compile time really exists. Plain unit
 * tests, no Spring context: Lombok's work is done before the program even runs.
 */
class LombokTest {

    private static final Order.OrderLine PEN = new Order.OrderLine("pen", 2, new BigDecimal("25.00"));

    @Test
    @DisplayName("@Builder + @Singular: build an order line by line")
    void builder() {
        Order order = Order.builder().id(1).customer("Asha").line(PEN).line(PEN).status(Order.Status.PLACED).build();

        assertThat(order.getLines()).hasSize(2);       // getter generated by @Value
        assertThat(order.total()).isEqualByComparingTo("100.00");
    }

    @Test
    @DisplayName("@Value: equals, hashCode and toString are generated from the fields")
    void valueObject() {
        Order a = Order.builder().id(1).customer("Asha").line(PEN).status(Order.Status.PLACED).build();
        Order b = Order.builder().id(1).customer("Asha").line(PEN).status(Order.Status.PLACED).build();

        assertThat(a).isEqualTo(b).hasSameHashCodeAs(b);
        assertThat(a.toString()).startsWith("Order(id=1, customer=Asha, lines=[");
    }

    @Test
    @DisplayName("@Value: every field is private final, no setters; the @Singular list can't be changed")
    void immutable() {
        for (Field field : Order.class.getDeclaredFields()) {
            if (!field.isSynthetic() && !Modifier.isStatic(field.getModifiers())) {
                assertThat(Modifier.isPrivate(field.getModifiers())).as(field.getName()).isTrue();
                assertThat(Modifier.isFinal(field.getModifiers())).as(field.getName()).isTrue();
            }
        }
        assertThat(Arrays.stream(Order.class.getMethods()).map(Method::getName)).noneMatch(n -> n.startsWith("set"));

        Order order = Order.builder().id(1).customer("Asha").line(PEN).status(Order.Status.PLACED).build();
        assertThatThrownBy(() -> order.getLines().add(PEN)).isInstanceOf(UnsupportedOperationException.class);
    }

    @Test
    @DisplayName("@Data: a mutable bean with getters AND setters")
    void dataBean() {
        OrderRequest request = new OrderRequest();          // @NoArgsConstructor
        request.setCustomer("Ravi");                        // setter from @Data
        request.setLines(List.of(new OrderRequest.Line("mouse", 1, new BigDecimal("999.00"))));

        assertThat(request.getCustomer()).isEqualTo("Ravi");
        assertThat(request).isEqualTo(new OrderRequest("Ravi", request.getLines())); // @AllArgsConstructor + equals
    }

    @Test
    @DisplayName("@Slf4j adds a static `log` field; @RequiredArgsConstructor adds the injection constructor")
    void generatedMembers() throws Exception {
        Field log = OrderService.class.getDeclaredField("log");
        assertThat(Modifier.isStatic(log.getModifiers())).isTrue();
        assertThat(log.getType().getName()).isEqualTo("org.slf4j.Logger");

        assertThat(OrderService.class.getConstructors()).singleElement()
                .satisfies(c -> assertThat(c.getParameterTypes()).hasSize(1)); // PaymentGateway
    }
}
