package jbdl.session09.orders;

import java.util.Map;
import java.util.NoSuchElementException;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicLong;
import jbdl.session09.aop.Audited;
import jbdl.session09.aop.Timed;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;

/**
 * Business code only: no timing, audit or retry code in here, yet all three happen (see the aspects).
 * Lombok: @RequiredArgsConstructor builds the constructor Spring injects PaymentGateway through;
 * @Slf4j adds `private static final Logger log`.
 */
@Slf4j
@Service
@RequiredArgsConstructor
public class OrderService {

    private final PaymentGateway payments;
    private final Map<Long, Order> orders = new ConcurrentHashMap<>();
    private final AtomicLong nextId = new AtomicLong(1);

    /** Creates the order, charges it and stores it as PAID. Audited and timed by the aspects. */
    @Timed
    @Audited(action = "ORDER_PLACED")
    public Order place(OrderRequest request) {
        if (request.getLines().isEmpty()) {
            throw new IllegalArgumentException("an order needs at least one line");
        }
        // Order.builder() is generated by Lombok's @Builder: set fields by name, then build()
        Order.OrderBuilder builder = Order.builder()
                .id(nextId.getAndIncrement())
                .customer(request.getCustomer())
                .status(Order.Status.PLACED);
        for (OrderRequest.Line line : request.getLines()) {
            builder.line(new Order.OrderLine(line.getProduct(), line.getQuantity(), line.getUnitPrice()));
        }
        Order order = builder.build();

        payments.charge(order.getId(), order.total()); // a call through the proxy: retried if flaky
        Order paid = order.withStatus(Order.Status.PAID);
        orders.put(paid.getId(), paid);
        log.info("order {} placed for {} (total {})", paid.getId(), paid.getCustomer(), paid.total());
        return paid;
    }

    public Order find(long id) {
        Order order = orders.get(id);
        if (order == null) {
            throw new NoSuchElementException("order " + id + " not found");
        }
        return order;
    }

    /**
     * The self-invocation trap: this.place(...) calls the real object, not the Spring proxy around it,
     * so the aspects do NOT run for the inner calls (no audit entries, no timing). Shown in the tests.
     */
    public int placeAll(Iterable<OrderRequest> requests) {
        int count = 0;
        for (OrderRequest request : requests) {
            place(request); // same as this.place(request): bypasses the proxy
            count++;
        }
        return count;
    }

    public void clear() {
        orders.clear();
        nextId.set(1);
    }
}
