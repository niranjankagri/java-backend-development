    password_hash varchar(100) not null
);

create table listing (
    id            bigint generated by default as identity primary key,
    host_id       bigint not null references app_user,
    title         varchar(120) not null,
    description   varchar(2000),
    city          varchar(80) not null,
    max_guests    integer not null,
    bedrooms      integer not null,
    nightly_price numeric(10, 2) not null,
    active        boolean not null,
    created_at    timestamp(6) with time zone not null
);
create index idx_listing_city on listing (city);

create table listing_amenity (
    listing_id bigint not null references listing,
    amenity    varchar(30) check (amenity in ('WIFI', 'KITCHEN', 'PARKING', 'AIR_CONDITIONING',
                                              'WASHING_MACHINE', 'WORKSPACE', 'POOL')),
    unique (listing_id, amenity)
);

create table booking (
    id          bigint generated by default as identity primary key,
    listing_id  bigint not null references listing,
    guest_id    bigint not null references app_user,
    check_in    date not null,
    check_out   date not null,
    guests      integer not null,
    total_price numeric(12, 2) not null,
    status      varchar(20) not null check (status in ('CONFIRMED', 'CANCELLED')),
    created_at  timestamp(6) with time zone not null,
    constraint ck_booking_dates check (check_out > check_in)
);
create index idx_booking_listing_dates on booking (listing_id, check_in, check_out);
create index idx_booking_guest on booking (guest_id);

create table review (
    id         bigint generated by default as identity primary key,
    booking_id bigint not null unique references booking,
    listing_id bigint not null references listing,
    rating     integer not null,
    comment    varchar(1000),
    created_at timestamp(6) with time zone not null,
    constraint ck_review_rating check (rating between 1 and 5)
);
create index idx_review_listing on review (listing_id);
